/**
 * The slugs a searched area may go by on listings and projects: "jumeirah-village-circle-jvc"
 * is also "jumeirah-village-circle" and "jvc", which is how the listings name it.
 */
export function areaSlugs(q: string): string[] {
  const area = dubaiAreas.find((a) => toSlug(a) === q);
  const short = area?.match(/^(.*?)\s*\(([^)]+)\)$/);
  return short ? [q, toSlug(short[1]), toSlug(short[2])] : [q];
}
